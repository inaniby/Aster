#!/bin/sh
# v0.23.20-dev (round 4) coverage for NARROW VALUES — the gap the A/B byte
# baseline could not see before this release.
#
# Round 3 fixed the u8-parameter defect; round 4's diagnosis (82 probes) showed
# why it had survived five releases: no example in the tree ever passed a u8/u16/
# i64 argument, so the 261-line A/B baseline (tests/baseline/.../example-hashes
# .txt, consumed by tests/struct-checks.sh [4/8]) was blind to that path. This
# release closes it two ways:
#   - four new examples (examples/narrow_*.ast) now carry narrow arguments,
#     returns and .so parameters, so the baseline records them byte for byte;
#   - this suite freezes the round-4 probes as a RESIDENT check whose expected
#     values are GENERATED BY aarch64 gcc at run time, never hand-computed.
#
# The discipline that matters: every case below has an Aster source AND an
# equivalent C source. The C source is the oracle. The suite compiles both,
# runs both under qemu, and asserts the two 8-bit exit codes are equal. No
# expected number is written down by hand — if Aster and gcc agree, the case
# passes; if they disagree, the case is a real defect, not a miscalculation.
# (Round 4's own hand-computed expectations produced three of its five "failures"
# before the bug was even looked at; this suite cannot repeat that mistake.)
#
# Layers:
#   [1] strict compiler build (-Werror)
#   [2] locate an AArch64 C compiler (the oracle); SKIP cleanly without one
#   [3] differential battery: narrow args/returns/struct-fields/arrays/loops/
#       recursion, each asserted equal to its C twin
#   [4] cross-language .so: Aster's .so called from a C host through dlopen/
#       dlsym, which is the only witness that Aster's narrow-argument STACK
#       LAYOUT matches the platform's (gcc's) — an Aster-calls-Aster test would
#       pass on a layout nothing else uses
set -eu
cd "$(dirname "$0")/.."
OUT=${OUT:-tmp-narrow-value-coverage}
W="$OUT/work"
mkdir -p "$W"; trap 'rm -rf "$OUT"' EXIT HUP INT TERM

# ---------------------------------------------------------------------------
printf '%s\n' '[1/4] Strictly build Aster compiler'
${CXX:-c++} -std=c++17 -O2 -Wall -Wextra -pedantic -Werror src/aster.cpp -o "$OUT/aster"

# ---------------------------------------------------------------------------
printf '%s\n' '[2/4] Locate an AArch64 C compiler (the independent oracle)'
HOSTCC=${HOSTCC:-}
if [ -z "$HOSTCC" ] && command -v aarch64-linux-gnu-gcc >/dev/null 2>&1; then
    HOSTCC=aarch64-linux-gnu-gcc
fi
if [ -z "$HOSTCC" ]; then
    echo "SKIP: narrow-value coverage needs an AArch64 C compiler (none found)"
    # A clean SKIP: the [3]/[4] layers are the only consumers of HOSTCC.
    exit 0
fi
# Confirm $HOSTCC actually emits AArch64; a native cc on an x86 box would pass
# the compile but produce binaries qemu-aarch64 cannot run.
printf 'int main(){return 0;}\n' > "$W/hostprobe.c"
if ! "$HOSTCC" -O2 -fwrapv "$W/hostprobe.c" -o "$W/hostprobe" 2>/dev/null \
   || ! readelf -h "$W/hostprobe" 2>/dev/null | grep -q 'AArch64'; then
    echo "SKIP: $HOSTCC does not emit AArch64 ELF (cross-compile toolchain missing)"
    exit 0
fi
printf '%s\n' "PASS: $HOSTCC emits AArch64 — differential oracle available"

# ---------------------------------------------------------------------------
# [3] Differential battery. Each case: an Aster source and a C source that
#     compute the same thing. The C source is compiled by $HOSTCC and run; its
#     exit code is the expected value. Aster's exit code must equal it.
# ---------------------------------------------------------------------------
printf '%s\n' '[3/4] Differential battery: narrow values, expected by gcc'
cat > "$W/cases.txt" <<'CASES_EOF'
11~u8_passthrough
fn g(a: u8) -> u8 { return a; }
fn main() -> i32 { return g(11); }
@C@
unsigned char g(unsigned char a){ return a; }
int main(void){ return g(11); }
@@@
12~u8_second_arg
fn g(a: u8, b: u8) -> u8 { return b; }
fn main() -> i32 { return g(100, 50); }
@C@
unsigned char g(unsigned char a, unsigned char b){ return b; }
int main(void){ return g(100, 50); }
@@@
13~u16_passthrough
fn g(a: u16) -> u16 { return a; }
fn main() -> i32 { return g(40000); }
@C@
unsigned short g(unsigned short a){ return a; }
int main(void){ return g(40000); }
@@@
14~i64_passthrough
fn g(a: i64) -> i64 { return a; }
fn main() -> i32 { return g(1234567890); }
@C@
long long g(long long a){ return a; }
int main(void){ return g(1234567890LL); }
@@@
15~mixed_narrow_args_return_i64
fn g(a: u8, b: u16, c: i64) -> i64 { return c; }
fn main() -> i32 { return g(1, 2, 1234567890); }
@C@
long long g(unsigned char a, unsigned short b, long long c){ return c; }
int main(void){ return (int)g(1, 2, 1234567890LL); }
@@@
16~narrow_arg_through_nested_call
fn g(a: u8) -> u8 { return a; }
fn h(b: i32) -> i32 { return g(200) + b * 0; }
fn main() -> i32 { return h(0); }
@C@
unsigned char g(unsigned char a){ return a; }
int h(int b){ return g(200) + b * 0; }
int main(void){ return h(0); }
@@@
17~i64_u8_combo
fn g(a: i64, b: u8) -> i32 { return (a - 1234567800) + b; }
fn main() -> i32 { return g(1234567890, 9); }
@C@
int g(long long a, unsigned char b){ return (int)(a - 1234567800LL) + b; }
int main(void){ return g(1234567890LL, 9); }
@@@
21~u8_ninth_arg
fn g(a: i32, b: i32, c: i32, d: i32, e: i32, f: i32, g: i32, h: i32, i: u8) -> i32 { return i; }
fn main() -> i32 { return g(0, 0, 0, 0, 0, 0, 0, 0, 77); }
@C@
int g(int a,int b,int c,int d,int e,int f,int gg,int h,unsigned char i){ return i; }
int main(void){ return g(0,0,0,0,0,0,0,0,77); }
@@@
22~u16_ninth_arg
fn g(a: i32, b: i32, c: i32, d: i32, e: i32, f: i32, g: i32, h: i32, i: u16) -> i32 { return i; }
fn main() -> i32 { return g(0, 0, 0, 0, 0, 0, 0, 0, 40000); }
@C@
int g(int a,int b,int c,int d,int e,int f,int gg,int h,unsigned short i){ return i; }
int main(void){ return g(0,0,0,0,0,0,0,0,40000); }
@@@
23~u8_u8_ninth_tenth_arg
fn g(a: i32, b: i32, c: i32, d: i32, e: i32, f: i32, g: i32, h: i32, i: u8, j: u8) -> i32 { return i + j; }
fn main() -> i32 { return g(0, 0, 0, 0, 0, 0, 0, 0, 30, 40); }
@C@
int g(int a,int b,int c,int d,int e,int f,int gg,int h,unsigned char i,unsigned char j){ return i + j; }
int main(void){ return g(0,0,0,0,0,0,0,0,30,40); }
@@@
24~narrow_return_used_in_i32
fn g(a: u8) -> u8 { return a; }
fn h(a: u8) -> i32 { return g(a) * 2; }
fn main() -> i32 { return h(40); }
@C@
unsigned char g(unsigned char a){ return a; }
int h(unsigned char a){ return g(a) * 2; }
int main(void){ return h(40); }
@@@
31~u8_struct_field
struct S { a: i32, b: u8 }
fn main() -> i32 { let s: S = S { 5, 200 }; return s.b; }
@C@
struct S { int a; unsigned char b; };
int main(void){ struct S s = { 5, 200 }; return s.b; }
@@@
32~u8_while_loop
fn main() -> i32 { let i: u8 = 0; let s: i32 = 0; while (i < 10) { s = s + i; i = i + 1; } return s; }
@C@
int main(void){ unsigned char i = 0; int s = 0; while (i < 10) { s = s + i; i = i + 1; } return s; }
@@@
33~u8_recursion
fn sum(a: u8, n: i32) -> i32 { if (n == 0) { return a; } else { return a + sum(a, n - 1); } }
fn main() -> i32 { return sum(10, 5); }
@C@
int sum(unsigned char a, int n){ if (n == 0) return a; else return a + sum(a, n - 1); }
int main(void){ return sum(10, 5); }
@@@
34~u8_global_array
let a: u8[700] = 0;
fn main() -> i32 { a[600] = 200; return a[600]; }
@C@
unsigned char a[700] = {0};
int main(void){ a[600] = 200; return a[600]; }
@@@
35~u16_global_array
let a: u16[300] = 0;
fn main() -> i32 { a[200] = 40000; return a[200]; }
@C@
unsigned short a[300] = {0};
int main(void){ a[200] = 40000; return a[200]; }
CASES_EOF

# Split the battery into per-case Aster and C files.
awk -v W="$W" '
  BEGIN { RS="@@@\n"; n=0 }
  {
    s = $0
    if (s !~ /^[0-9]/) next
    nl = index(s, "\n")
    if (nl <= 0) next
    hdr = substr(s, 1, nl - 1)
    split(hdr, hh, "~"); code = hh[1]
    rest = substr(s, nl + 1)
    cpos = index(rest, "@C@")
    if (cpos <= 0) next
    ast = substr(rest, 1, cpos - 1)
    csrc = substr(rest, cpos + 3)
    printf "%s", ast  > (W "/c" code ".ast")
    printf "%s", csrc > (W "/c" code ".c")
    print code >> (W "/codelist.txt")
    n++
  }
  END { close(W "/codelist.txt") }
' "$W/cases.txt"
printf '%s\n' "PASS: $(wc -l < "$W/codelist.txt") differential cases split into Aster + C pairs"

diff_ok=0; diff_bad=0
while read -r code; do
    # Aster side.
    if ! "$OUT/aster" build-elf "$W/c$code.ast" -o "$W/c$code.a64" >"$W/c$code.aster.log" 2>&1; then
        echo "FAIL: case $code: Aster did not compile:" >&2
        tail -n 5 "$W/c$code.aster.log" >&2
        exit 1
    fi
    # C oracle side.
    if ! "$HOSTCC" -O2 -fwrapv "$W/c$code.c" -o "$W/c$code.cbin" >"$W/c$code.c.log" 2>&1; then
        echo "FAIL: case $code: C oracle did not compile:" >&2
        tail -n 5 "$W/c$code.c.log" >&2
        exit 1
    fi
    agot=0; sh tests/run-aarch64.sh "$W/c$code.a64" >/dev/null 2>&1 || agot=$?
    cgot=0; sh tests/run-aarch64.sh "$W/c$code.cbin" >/dev/null 2>&1 || cgot=$?
    if [ "$agot" != "$cgot" ]; then
        echo "FAIL: case $code: Aster exit $agot != gcc exit $cgot (narrow layout/value mismatch)" >&2
        diff_bad=$((diff_bad + 1))
    else
        diff_ok=$((diff_ok + 1))
    fi
done < "$W/codelist.txt"
if [ "$diff_bad" -ne 0 ]; then
    echo "FAIL: $diff_bad differential case(s) disagree with gcc" >&2
    exit 1
fi
printf 'PASS: %d narrow-value expressions match aarch64 gcc exactly (args, returns, struct fields, arrays, loops, recursion)\n' "$diff_ok"

# ---------------------------------------------------------------------------
# [4] Cross-language .so: Aster exports narrow-param functions in a shared
#     object; a C host loads it with dlopen/dlsym and calls them. This is the
#     only check that proves Aster's narrow-argument STACK LAYOUT is the one
#     the platform (gcc) actually uses — the 9th argument's offset, the
#     register-to-stack split, the high bits of a returned u8. Aster-calls-
#     Aster cannot see a layout mismatch because both sides would use the same
#     (possibly wrong) layout.
# ---------------------------------------------------------------------------
printf '%s\n' '[4/4] Cross-language .so: Aster narrow params called from C via dlopen'
# The .so source is the same one recorded in the A/B baseline (examples/
# narrow_so.ast), so this test also guards that baseline example's emission.
if ! "$OUT/aster" build-so examples/narrow_so.ast -o "$W/libnarrow.so" --soname libnarrow.so \
        >"$W/so.log" 2>&1; then
    echo "FAIL: could not build the narrow-parameter .so:" >&2
    cat "$W/so.log" >&2
    exit 1
fi
cat > "$W/so_host.c" <<'CHOST'
#include <stdio.h>
#include <dlfcn.h>
int main(void){
    void* h = dlopen("__LIB__", RTLD_NOW);
    if (!h) { fprintf(stderr, "dlopen: %s\n", dlerror()); return 99; }
    unsigned char  (*add_u8) (unsigned char, unsigned char) = dlsym(h, "add_u8");
    unsigned short (*add_u16)(unsigned short, unsigned short) = dlsym(h, "add_u16");
    long long      (*scale_i64)(long long, long long) = dlsym(h, "scale_i64");
    unsigned char  (*ninth_u8)(int,int,int,int,int,int,int,int,unsigned char) = dlsym(h, "ninth_u8");
    unsigned char  (*ret_u8)(void) = dlsym(h, "ret_u8");
    unsigned short (*ret_u16)(void) = dlsym(h, "ret_u16");
    int bad = 0;
    if (add_u8(100, 50) != 150)            bad |= 1;
    if (add_u16(40000, 25535) != 65535)    bad |= 2;
    if (scale_i64(1000000, 7) != 7000000LL) bad |= 4;
    if (ninth_u8(0,0,0,0,0,0,0,0,200) != 200) bad |= 8;
    if (ret_u8() != 200)                   bad |= 16;
    if (ret_u16() != 40000)                bad |= 32;
    return bad;
}
CHOST
# Point the host at the .so we just built (absolute path, so dlopen cannot
# accidentally open the main binary the way a NULL path would).
sed -i "s|__LIB__|$W/libnarrow.so|" "$W/so_host.c"
if ! "$HOSTCC" -O2 -fwrapv "$W/so_host.c" -o "$W/so_host" -ldl >"$W/so_host.log" 2>&1; then
    echo "FAIL: C host for the narrow-parameter .so did not compile:" >&2
    cat "$W/so_host.log" >&2
    exit 1
fi
got=0; sh tests/run-aarch64.sh "$W/so_host" >/dev/null 2>&1 || got=$?
if [ "$got" -ne 0 ]; then
    echo "FAIL: cross-language narrow-parameter .so call returned $got (expected 0)" >&2
    echo "----- the C host asserts: add_u8(100,50)==150, add_u16(40000,25535)==65535," >&2
    echo "      scale_i64(1e6,7)==7e6, ninth_u8(...,200)==200, ret_u8()==200, ret_u16()==40000" >&2
    exit 1
fi
printf 'PASS: Aster .so called from C (dlopen/dlsym): 6 narrow-param signatures agree with the platform\n'
printf '%s\n' 'ALL NARROW-VALUE COVERAGE CHECKS PASSED'
